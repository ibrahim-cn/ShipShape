import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def read(relative):
    return (ROOT / relative).read_text()


def count_files():
    return sorted(path.relative_to(ROOT).as_posix() for path in ROOT.rglob("*") if path.is_file())


backend_exit = read("backend/backend-tests.exit-code.txt").strip()
backend_summary = read("backend/test-summary.txt")
backend_match = re.search(r"Aggregate[\s\S]*?tests=(\d+), failures=(\d+), errors=(\d+), skipped=(\d+)", backend_summary)
backend_ok = backend_exit == "0" and backend_match and backend_match.group(2) == backend_match.group(3) == backend_match.group(4) == "0"
backend_tests = backend_match.group(1) if backend_match else "unknown"

api_rows = [line for line in read("api/request-summary.md").splitlines() if line.startswith("| TC-")]
api_ok = len(api_rows) == 44 and all(line.rstrip().endswith("PASS |") for line in api_rows)
api_report = read("api/assertion-report.txt")

browser = json.loads(read("frontend/browser-verification.json"))
browser_ok = len(browser["cases"]) == 8 and all(case["status"] == "PASS" for case in browser["cases"]) and not browser["page_errors"]

matrix_report = read("matrix-assertion-report.txt")
matrix_ok = "unique_ids=True" in matrix_report and "assertion_failures=none" in matrix_report

performance = read("performance/performance-summary.txt")
performance_ok = "Result: PASS" in performance and "Failures: none" in performance

diff_check_exit = read("final-verification/git-diff-check.exit-code.txt").strip()
ports_lines = [line for line in read("final-verification/ports-after-stop.txt").splitlines() if line.strip()]
final_ok = diff_check_exit == "0" and not ports_lines

checks = {
    "backend": backend_ok,
    "api": api_ok,
    "browser": browser_ok,
    "matrix": matrix_ok,
    "performance": performance_ok,
    "final": final_ok,
}
if not all(checks.values()):
    raise SystemExit("README assertions failed: {}".format(checks))

files = count_files()
lines = [
    "# Week 6 evidence",
    "",
    "This directory contains only Week 6 testing and validation artifacts. Historical weekly evidence and report files were not modified.",
    "",
    "Summary:",
    "",
    "- Backend: {} tests, 0 failures/errors/skipped, Java 17.".format(backend_tests),
    "- Frontend: production build exit code 0; browser verification 8/8 PASS with no page errors; website case asserts submitted/final scheme display.",
    "- Live API: 44 functional/negative/boundary/security cases; all matched assertions generated by `api/generate-request-summary.py`.",
    "- Performance: five distinct public URLs; maximum total app-reported website duration 962 ms, below the 10 s target.",
    "- Correctness audit: five application behavior defects were reproduced before correction, minimally corrected, and retested; see `debugging/failure-diagnosis.md`.",
    "- Evidence integrity: request summary, matrix, performance summary, and browser checks are generated from assertions; duplicate IDs and failures are reported by `api/assertion-report.txt` and `matrix-assertion-report.txt`.",
    "- Requirement status: NFR-01 fully verified for low-volume observations; NFR-02 and NFR-03 partially verified; FR-05 partially verified because the frontend has a textarea rather than a file picker.",
    "- Security: live SSRF/path/parser checks passed; private-DNS, public-redirect-to-internal, and pinned connection-stage scenarios remain documented limitations.",
    "- Servers started for Week 6 were stopped; no listeners remain on 8080 or 5173.",
    "- Git: no commit/push/merge/reset/branch switch; `git diff --check` exit code 0.",
    "",
    "File inventory ({} files):".format(len(files)),
    "",
]
lines.extend("- `{}`".format(path) for path in files)
(ROOT / "README.md").write_text("\n".join(lines) + "\n")
print("readme_files={} assertions={}".format(len(files), "PASS"))
